#include <stdio.h>

int main()
{
    // กำนหดตัวแปร ตัวเลข
    int age = 20;
  
    // กำหนดตัวแปร จำนวนทิศนิยม
    float height = 5.7;
  
    // กำหนดตัวแปร ตัวอักษร
    char grade = 'A';
  
    printf("Age: %d\n", age);
    printf("Height: %.1f\n", height);
    printf("Grade: %c\n", grade);
  
    return 0;
}
